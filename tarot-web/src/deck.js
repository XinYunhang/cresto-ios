// 56 张小牌（数字牌 1~10 + 宫廷牌 11~14）
for (const [suitEn, suitZh, filePrefix] of SUITS) {
  MINOR_MEANINGS[filePrefix].forEach(([kwUp, kwRev, up, rev], idx) => {
    const rank = idx + 1
    const [num, enWord, zhWord, enPrefix] = RANKS[rank - 1]
    const nameEn = rank <= 10 ? `${enWord} OF ${suitEn}` : `${enPrefix} ${suitEn}`
    deck.push({
      id: `${filePrefix}-${String(rank).padStart(2, '0')}`,
      number: num,
      nameEn,
      nameZh: `${suitZh}${zhWord}`,
      suit: filePrefix,
      image: `cards/${filePrefix}-${String(rank).padStart(2, '0')}.jpg`,
      keywordsUp: kwUp,
      keywordsRev: kwRev,
      meaningUp: up,
      meaningRev: rev
    })
  })
}

